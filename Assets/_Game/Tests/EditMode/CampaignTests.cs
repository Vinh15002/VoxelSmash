using System.Collections.Generic;
using System.Linq;
using NUnit.Framework;
using UnityEditor;
using UnityEngine;
using VoxelSmash.Core;

namespace VoxelSmash.Tests
{
    public class CampaignTests
    {
        static readonly Vector3Int[] Neighbours =
        {
            new(1, 0, 0), new(-1, 0, 0), new(0, 1, 0), new(0, -1, 0), new(0, 0, 1), new(0, 0, -1)
        };

        [Test]
        public void PackedVoxelsRoundTrip()
        {
            var model = ScriptableObject.CreateInstance<VoxelModel>();
            model.voxels = new[] { new Voxel(-300, 0, 12, 29, .95f), new Voxel(5, 77, -1, 3, 1.04f) };
            var back = model.voxels;
            Assert.AreEqual(2, model.VoxelCount);
            Assert.AreEqual(-300, back[0].x);
            Assert.AreEqual(77, back[1].y);
            Assert.AreEqual(29, back[0].color);
            Assert.AreEqual(1.04f, back[1].shade, .002f);
            Object.DestroyImmediate(model);
        }

        // Generated by ProjectSetup.Run: 200 levels, each with its own model, every model standing up.
        [Test]
        public void TwoHundredDistinctStandingLevels()
        {
            var list = AssetDatabase.LoadAssetAtPath<LevelList>("Assets/_Game/Data/Levels.asset");
            Assert.AreEqual(200, list.Length);
            var used = Enumerable.Range(1, list.Length).Select(list.ModelFor).ToList();
            Assert.AreEqual(200, used.Distinct().Count(), "a model repeats within the campaign");
            Assert.AreEqual(40, Enumerable.Range(1, 200).Count(list.IsBoss));
            foreach (var model in used)
            {
                var cells = new HashSet<Vector3Int>(model.voxels.Select(v => v.Grid));
                var reached = new HashSet<Vector3Int>(cells.Where(c => c.y == 0));
                var queue = new Queue<Vector3Int>(reached);
                while (queue.Count > 0)
                {
                    var c = queue.Dequeue();
                    foreach (var n in Neighbours)
                        if (cells.Contains(c + n) && reached.Add(c + n)) queue.Enqueue(c + n);
                }
                Assert.AreEqual(cells.Count, reached.Count, $"{model.displayName} has floating voxels");
                Assert.Less(model.voxels.Max(v => v.color), model.palette.Length, $"{model.displayName} uses a missing colour");
            }
        }
    }
}
